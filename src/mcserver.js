//  RconConnection  (internal class, not exported)
// ══════════════════════════════════════════════════════════════════════════════
class RconConnection {
  constructor(host, port, password) {
    this.host          = host;
    this.port          = port;
    this.password      = password;
    this.socket        = null;
    this.connected     = false;
    this.authenticated = false;
    this._id           = 0;
    this._pending      = new Map();
    this._buf          = Buffer.alloc(0);
  }

  connect() {
    return new Promise((resolve, reject) => {
      this.socket = net.createConnection({ host: this.host, port: this.port });
      this.socket.on('connect', async () => {
        this.connected = true;
        try {
          await this._write(3, this.password); // SERVERDATA_AUTH
          this.authenticated = true;
          resolve();
        } catch (e) { reject(e); }
      });
      this.socket.on('data', (chunk) => {
        this._buf = Buffer.concat([this._buf, chunk]);
        this._drain();
      });
      this.socket.on('error',  reject);
      this.socket.on('close', () => { this.connected = false; });
      this.socket.setTimeout(5000, () => reject(new Error('RCON timeout')));
    });
  }

  _drain() {
    while (this._buf.length >= 14) {
      const size = this._buf.readInt32LE(0);
      if (this._buf.length < size + 4) break;
      const id   = this._buf.readInt32LE(4);
      // const type = this._buf.readInt32LE(8);  // not needed
      const body = this._buf.slice(12, 4 + size - 2).toString('utf8');
      this._buf  = this._buf.slice(4 + size);
      const cb   = this._pending.get(id);
      if (cb) { this._pending.delete(id); cb(null, body); }
    }
  }

  _write(type, body) {
    return new Promise((resolve, reject) => {
      const id    = ++this._id;
      const bBody = Buffer.from(body, 'utf8');
      const pkt   = Buffer.alloc(14 + bBody.length);
      pkt.writeInt32LE(10 + bBody.length, 0); // size field
      pkt.writeInt32LE(id,   4);
      pkt.writeInt32LE(type, 8);
      bBody.copy(pkt, 12);
      pkt.writeInt16LE(0, 12 + bBody.length); // null terminators
      this._pending.set(id, (err, res) => err ? reject(err) : resolve(res));
      this.socket.write(pkt);
    });
  }

  command(cmd) {
    if (!this.connected || !this.authenticated)
      throw new Error('[mcserver] RCON is not connected / authenticated.');
    return this._write(2, cmd); // SERVERDATA_EXECCOMMAND
  }

  disconnect() {
    if (this.socket) this.socket.destroy();
    this.connected = false;
  }
}


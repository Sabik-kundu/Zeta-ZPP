//  ServerInstance  (internal class, not exported)
// ══════════════════════════════════════════════════════════════════════════════
class ServerInstance extends EventEmitter {
  constructor(id, dir, opts) {
    super();
    this.id      = id;
    this.dir     = dir;
    this.opts    = opts;
    this.process = null;
    this.running = false;
    this.players = new Set();
    this.log     = [];          // circular buffer, max 2 000 lines
    this.type    = opts.type    || 'vanilla';
    this.version = opts.version || 'latest';
    this.jarFile = opts.jarFile || 'server.jar';
  }

  /** Start the Minecraft server process. */
  start(extraJvmArgs = []) {
    if (this.running) throw new Error(`[mcserver] Server ${this.id} is already running.`);
    const jar = path.join(this.dir, this.jarFile);
    if (!fs.existsSync(jar))
      throw new Error(`[mcserver] JAR not found at ${jar} — did you call __download_server_jar first?`);

    // Auto-accept EULA
    fs.writeFileSync(path.join(this.dir, 'eula.txt'), 'eula=true\n');

    const maxRam = this.opts.ram    || '2G';
    const minRam = this.opts.minRam || '512M';
    const jvmArgs = [
      `-Xms${minRam}`, `-Xmx${maxRam}`,
      // G1GC tuning — helps with big modpacks
      '-XX:+UseG1GC',
      '-XX:+ParallelRefProcEnabled',
      '-XX:MaxGCPauseMillis=200',
      '-XX:+UnlockExperimentalVMOptions',
      '-XX:+DisableExplicitGC',
      '-XX:+AlwaysPreTouch',
      '-XX:G1NewSizePercent=30',
      '-XX:G1MaxNewSizePercent=40',
      '-XX:G1HeapRegionSize=8M',
      '-XX:G1ReservePercent=20',
      '-XX:G1HeapWastePercent=5',
      '-XX:G1MixedGCCountTarget=4',
      '-XX:InitiatingHeapOccupancyPercent=15',
      '-XX:G1MixedGCLiveThresholdPercent=90',
      '-XX:G1RSetUpdatingPauseTimePercent=5',
      '-XX:SurvivorRatio=32',
      '-XX:+PerfDisableSharedMem',
      '-XX:MaxTenuringThreshold=1',
      '-Dusing.aikars.flags=https://mcflags.emc.gs',
      ...extraJvmArgs,
      '-jar', jar, '--nogui',
    ];

    this.process = childProcess.spawn('java', jvmArgs, {
      cwd:   this.dir,
      stdio: ['pipe', 'pipe', 'pipe'],
    });
    this.running = true;

    // Attach readline to both stdout and stderr
    const attachReader = (stream) => {
      readline.createInterface({ input: stream, crlfDelay: Infinity })
        .on('line', (line) => {
          // Store line
          this.log.push({ time: Date.now(), line });
          if (this.log.length > 2000) this.log.shift();
          this.emit('log', line);

          // ── Parse key events ──────────────────────────────
          // Player join
          const joinMatch = line.match(/\[.+?\] \[.+?\/INFO\]: (.+) joined the game/);
          if (joinMatch) {
            this.players.add(joinMatch[1]);
            this.emit('player_join', joinMatch[1]);
          }
          // Player leave
          const leaveMatch = line.match(/\[.+?\] \[.+?\/INFO\]: (.+) left the game/);
          if (leaveMatch) {
            this.players.delete(leaveMatch[1]);
            this.emit('player_leave', leaveMatch[1]);
          }
          // Chat
          const chatMatch = line.match(/\[.+?\/INFO\]: <(\w+)>\s(.+)/);
          if (chatMatch) this.emit('chat', { player: chatMatch[1], message: chatMatch[2] });
          // Server ready
          if (line.includes('Done (') && line.includes('For help, type "help"'))
            this.emit('ready');
          // Crash / error
          if (line.includes('FAILED TO BIND TO PORT'))
            this.emit('error', new Error('Port already in use'));
        });
    };

    attachReader(this.process.stdout);
    attachReader(this.process.stderr);

    this.process.on('close', (code) => {
      this.running = false;
      this.players.clear();
      this.emit('stop', code);
    });
  }

  /** Write a command to the server stdin. */
  command(cmd) {
    if (!this.running || !this.process)
      throw new Error(`[mcserver] Server ${this.id} is not running.`);
    this.process.stdin.write(cmd.trim() + '\n');
  }

  /** Stop the server (graceful or force). */
  stop(force = false) {
    if (!this.running || !this.process) return;
    if (force) this.process.kill('SIGKILL');
    else       this.process.stdin.write('stop\n');
  }
}


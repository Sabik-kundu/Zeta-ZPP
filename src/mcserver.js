/**
 * Check if a port is free (true = free, false = in use).
 * @param {number} port
 * @returns {Promise<boolean>}
 */
function __check_port(port) {
  return new Promise(resolve => {
    const s = net.createServer();
    s.once('error', () => resolve(false));
    s.once('listening', () => { s.close(); resolve(true); });
    s.listen(port);
  });
}

/**
 * Get host system information.
 * @returns {{ totalMemGB, freeMemGB, cpus, platform, arch, uptimeHours }}
 */
function __system_info() {
  return {
    totalMemGB:  +(os.totalmem()  / 1073741824).toFixed(2),
    freeMemGB:   +(os.freemem()   / 1073741824).toFixed(2),
    cpus:        os.cpus().length,
    platform:    os.platform(),
    arch:        os.arch(),
    uptimeHours: +(os.uptime() / 3600).toFixed(2),
  };
}


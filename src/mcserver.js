/**
 * Back up the world folder to a .tar.gz archive in the server's backups/ directory.
 *
 * @param {string} serverId
 * @param {string} [backupName]  Optional filename (auto-generated from timestamp otherwise)
 * @returns {string} path to the backup archive
 */
async function __backup_world(serverId, backupName) {
  const inst  = _MC_SERVERS.get(serverId);
  if (!inst) throw new Error(`[mcserver] Unknown server: ${serverId}`);
  const world = __get_property(serverId, 'level-name') || 'world';
  const bkDir = path.join(inst.dir, 'backups');
  fs.mkdirSync(bkDir, { recursive: true });
  const fname = backupName || `world-backup-${new Date().toISOString().replace(/[:.]/g, '-')}.tar.gz`;
  const dest  = path.join(bkDir, fname);
  await new Promise((resolve, reject) => {
    const p = childProcess.spawn('tar', ['-czf', dest, '-C', inst.dir, world]);
    p.on('close', code => code === 0 ? resolve() : reject(new Error(`tar exited ${code}`)));
  });
  return dest;
}

/**
 * Restore a world from a .tar.gz backup.
 * The server must be stopped first.
 */
async function __restore_world(serverId, backupFilePath) {
  const inst = _MC_SERVERS.get(serverId);
  if (!inst) throw new Error(`[mcserver] Unknown server: ${serverId}`);
  if (inst.running) throw new Error('[mcserver] Stop the server before restoring a world.');
  const world = __get_property(serverId, 'level-name') || 'world';
  const wd    = path.join(inst.dir, world);
  if (fs.existsSync(wd)) fs.rmSync(wd, { recursive: true });
  await new Promise((resolve, reject) => {
    const p = childProcess.spawn('tar', ['-xzf', backupFilePath, '-C', inst.dir]);
    p.on('close', code => code === 0 ? resolve() : reject(new Error(`tar exited ${code}`)));
  });
  return true;
}

/**
 * List all backups for a server.
 * @returns {{ name, path, sizeMB, created }[]}
 */
function __list_backups(serverId) {
  const inst   = _MC_SERVERS.get(serverId);
  if (!inst) throw new Error(`[mcserver] Unknown server: ${serverId}`);
  const bkDir  = path.join(inst.dir, 'backups');
  if (!fs.existsSync(bkDir)) return [];
  return fs.readdirSync(bkDir).map(f => {
    const full = path.join(bkDir, f);
    const st   = fs.statSync(full);
    return { name: f, path: full, sizeMB: +(st.size / 1048576).toFixed(2), created: st.mtime };
  });
}

/** Delete a specific backup by filename. */
function __delete_backup(serverId, backupFilename) {
  const inst = _MC_SERVERS.get(serverId);
  if (!inst) throw new Error(`[mcserver] Unknown server: ${serverId}`);
  const p = path.join(inst.dir, 'backups', backupFilename);
  if (!fs.existsSync(p)) throw new Error(`[mcserver] Backup not found: ${backupFilename}`);
  fs.unlinkSync(p);
  return true;
}


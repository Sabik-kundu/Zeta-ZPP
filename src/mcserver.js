/**
 * Search Modrinth for mods, plugins, resource packs, or modpacks.
 *
 * @param {string}  query
 * @param {string}  [mcVersion]  Filter by MC version
 * @param {string}  [loader]     'fabric' | 'forge' | 'neoforge' | 'bukkit' | 'paper' etc.
 * @param {string}  [type]       'mod' | 'plugin' | 'resourcepack' | 'modpack'  (default: 'mod')
 * @param {number}  [limit]      Max results (default: 10)
 * @returns {object[]}
 */
async function __search_modrinth(query, mcVersion, loader, type = 'mod', limit = 10) {
  const facets = [];
  if (mcVersion) facets.push([`versions:${mcVersion}`]);
  if (loader)    facets.push([`categories:${loader}`]);
  facets.push([`project_type:${type}`]);

  const url = `${MODRINTH_API}/search?query=${encodeURIComponent(query)}&limit=${limit}&facets=${encodeURIComponent(JSON.stringify(facets))}`;
  const raw  = JSON.parse(await _fetch(url));
  return raw.hits.map(h => ({
    id:          h.project_id,
    slug:        h.slug,
    title:       h.title,
    description: h.description,
    downloads:   h.downloads,
    follows:     h.follows,
    versions:    h.versions,
    categories:  h.categories,
    iconUrl:     h.icon_url,
    projectType: h.project_type,
    pageUrl:     `https://modrinth.com/mod/${h.slug}`,
  }));
}

/**
 * Install a mod or plugin from Modrinth by project ID or slug.
 * Automatically picks the latest version compatible with the server's MC version.
 *
 * @param {string} serverId
 * @param {string} projectIdOrSlug  e.g. 'fabric-api' or 'P7dR8mSH'
 * @returns {{ file, version, dest }}
 */
async function __install_from_modrinth(serverId, projectIdOrSlug) {
  const inst = _MC_SERVERS.get(serverId);
  if (!inst) throw new Error(`[mcserver] Unknown server: ${serverId}`);

  const mc     = inst.version;
  const loader = inst.type === 'fabric'    ? 'fabric'   :
                 inst.type === 'neoforge'  ? 'neoforge' :
                 inst.type === 'paper'     ? 'paper'    :
                 inst.type === 'purpur'    ? 'purpur'   : null;

  let versUrl = `${MODRINTH_API}/project/${projectIdOrSlug}/version?game_versions=${encodeURIComponent(JSON.stringify([mc]))}`;
  if (loader) versUrl += `&loaders=${encodeURIComponent(JSON.stringify([loader]))}`;

  const versions = JSON.parse(await _fetch(versUrl));
  if (!versions || !versions.length)
    throw new Error(`[mcserver] No Modrinth version found for "${projectIdOrSlug}" on MC ${mc} / ${loader}`);

  const best = versions[0];
  const file = best.files.find(f => f.primary) || best.files[0];

  const isPlugin  = ['paper', 'purpur', 'bukkit', 'spigot'].includes(loader);
  const targetDir = isPlugin
    ? path.join(inst.dir, 'plugins')
    : path.join(inst.dir, 'mods');
  fs.mkdirSync(targetDir, { recursive: true });

  const dest = path.join(targetDir, file.filename);
  await _download(file.url, dest);
  return { file: file.filename, version: best.version_number, dest };
}


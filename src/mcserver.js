/**
 * Get available Minecraft versions.
 * @param {'release'|'snapshot'|'all'} type
 * @returns {{ latest: object, versions: object[] }}
 */
async function __get_versions(type = 'release') {
  const mf = await _manifest();
  const vs  = type === 'all' ? mf.versions : mf.versions.filter(v => v.type === type);
  return {
    latest:   mf.latest,
    versions: vs.map(v => ({ id: v.id, type: v.type, releaseTime: v.releaseTime })),
  };
}


/** Write any file inside the server's directory (e.g. config files). */
function __write_server_file(serverId, relPath, content) {
  const inst = _MC_SERVERS.get(serverId);
  if (!inst) throw new Error(`[mcserver] Unknown server: ${serverId}`);
  const full = path.join(inst.dir, relPath);
  fs.mkdirSync(path.dirname(full), { recursive: true });
  fs.writeFileSync(full, content);
  return full;
}

/** Read any file from inside the server's directory. */
function __read_server_file(serverId, relPath) {
  const inst = _MC_SERVERS.get(serverId);
  if (!inst) throw new Error(`[mcserver] Unknown server: ${serverId}`);
  const full = path.join(inst.dir, relPath);
  if (!fs.existsSync(full)) throw new Error(`[mcserver] File not found: ${relPath}`);
  return fs.readFileSync(full, 'utf8');
}

/** Get the absolute path to the server directory. */
function __server_dir(serverId) {
  const inst = _MC_SERVERS.get(serverId);
  if (!inst) throw new Error(`[mcserver] Unknown server: ${serverId}`);
  return inst.dir;
}


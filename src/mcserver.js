/** HTTP/HTTPS GET → resolves to response body string.  Follows redirects. */
function _fetch(url) {
  return new Promise((resolve, reject) => {
    const mod = url.startsWith('https') ? https : http;
    mod.get(url, { headers: { 'User-Agent': 'ZPP-MCServer/1.0' } }, (res) => {
      if (res.statusCode >= 300 && res.statusCode < 400 && res.headers.location) {
        return _fetch(res.headers.location).then(resolve).catch(reject);
      }
      let raw = '';
      res.on('data', c => raw += c);
      res.on('end',  () => resolve(raw));
    }).on('error', reject);
  });
}

/** Download a remote URL to a local file path.  Follows redirects. */
function _download(url, dest) {
  return new Promise((resolve, reject) => {
    const mod  = url.startsWith('https') ? https : http;
    const file = fs.createWriteStream(dest);
    mod.get(url, { headers: { 'User-Agent': 'ZPP-MCServer/1.0' } }, (res) => {
      if (res.statusCode >= 300 && res.statusCode < 400 && res.headers.location) {
        file.close();
        try { fs.unlinkSync(dest); } catch (_) {}
        return _download(res.headers.location, dest).then(resolve).catch(reject);
      }
      res.pipe(file);
      file.on('finish', () => file.close(resolve));
      file.on('error',  reject);
    }).on('error', (e) => { try { fs.unlinkSync(dest); } catch (_) {} reject(e); });
  });
}

/** Parse a server.properties file into a plain object. */
function _readProps(filePath) {
  if (!fs.existsSync(filePath)) return {};
  return fs.readFileSync(filePath, 'utf8')
    .split('\n')
    .filter(l => l.includes('=') && !l.trimStart().startsWith('#'))
    .reduce((acc, l) => {
      const eq = l.indexOf('=');
      acc[l.slice(0, eq).trim()] = l.slice(eq + 1).trim();
      return acc;
    }, {});
}

/** Write a plain object back to a server.properties file. */
function _writeProps(filePath, props) {
  const lines = [
    '#Minecraft server properties',
    `#Generated by ZPP mcserver.zl  ${new Date().toISOString()}`,
    ...Object.entries(props).map(([k, v]) => `${k}=${v}`),
  ];
  fs.writeFileSync(filePath, lines.join('\n') + '\n');
}

/** Check whether the system Java meets a minimum major version. */
function _javaCheck(min = 17) {
  try {
    const out   = childProcess.execSync('java -version 2>&1', { encoding: 'utf8' });
    const match = out.match(/version "(\d+)/);
    const ver   = match ? parseInt(match[1]) : 0;
    return { available: true, version: ver, meets: ver >= min };
  } catch {
    return { available: false, version: 0, meets: false };
  }
}

/** Get the Mojang version manifest (cached per process run). */
let _manifestCache = null;
async function _manifest() {
  if (!_manifestCache) {
    _manifestCache = JSON.parse(await _fetch(MOJANG_MANIFEST));
  }
  return _manifestCache;
}

/** Resolve 'latest' / 'latest_snapshot' / a real version ID. */
async function _resolveVersion(requested) {
  const m = await _manifest();
  if (!requested || requested === 'latest')          return m.latest.release;
  if (requested === 'latest_snapshot')               return m.latest.snapshot;
  const found = m.versions.find(v => v.id === requested);
  if (!found) throw new Error(`Minecraft version "${requested}" not found`);
  return found.id;
}


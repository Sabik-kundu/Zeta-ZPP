/**
 * Install Fabric on a server.
 * Downloads Fabric's self-contained server launcher JAR — no separate installer needed.
 *
 * @param {string} serverId
 * @param {string} [mcVersion]     Defaults to server's current version
 * @param {string} [loaderVersion] Defaults to latest stable
 * @returns {{ loaderVersion, installerVersion, mcVersion }}
 */
async function __install_fabric(serverId, mcVersion, loaderVersion) {
  const inst = _MC_SERVERS.get(serverId);
  if (!inst) throw new Error(`[mcserver] Unknown server: ${serverId}`);

  const mc       = await _resolveVersion(mcVersion || inst.version);
  const loaders  = JSON.parse(await _fetch(`${FABRIC_META}/v2/versions/loader/${mc}`));
  if (!loaders.length) throw new Error(`[mcserver] No Fabric loader found for MC ${mc}`);
  const lv       = loaderVersion || loaders[0].loader.version;
  const installs = JSON.parse(await _fetch(`${FABRIC_META}/v2/versions/installer`));
  const iv       = installs[0].version;

  const dest = path.join(inst.dir, 'fabric-server.jar');
  await _download(`${FABRIC_META}/v2/versions/loader/${mc}/${lv}/${iv}/server/jar`, dest);

  inst.type    = 'fabric';
  inst.jarFile = 'fabric-server.jar';
  inst.version = mc;
  fs.mkdirSync(path.join(inst.dir, 'mods'), { recursive: true });
  return { loaderVersion: lv, installerVersion: iv, mcVersion: mc };
}

/**
 * Install NeoForge on a server.
 * Downloads the NeoForge installer and runs it in --installServer mode.
 *
 * @param {string} serverId
 * @param {string} [mcVersion]       Defaults to server's current version
 * @param {string} [neoforgeVersion] Defaults to latest compatible
 * @returns {{ neoforgeVersion, mcVersion }}
 */
async function __install_neoforge(serverId, mcVersion, neoforgeVersion) {
  const inst = _MC_SERVERS.get(serverId);
  if (!inst) throw new Error(`[mcserver] Unknown server: ${serverId}`);

  const mc       = await _resolveVersion(mcVersion || inst.version);
  // NeoForge versions are named after the MC minor+patch, e.g. 21.4.x for 1.21.4
  const nfBase   = mc.replace(/^1\./, '');
  const metaUrl  = `${NEOFORGE_MAVEN}/api/maven/versions/releases/net/neoforged/neoforge`;
  const meta     = JSON.parse(await _fetch(metaUrl));
  const compat   = (meta.versions || []).filter(v => v.startsWith(nfBase)).sort().reverse();
  if (!compat.length) throw new Error(`[mcserver] No NeoForge release for MC ${mc}`);
  const nfv      = neoforgeVersion || compat[0];

  const installerUrl  = `${NEOFORGE_MAVEN}/releases/net/neoforged/neoforge/${nfv}/neoforge-${nfv}-installer.jar`;
  const installerDest = path.join(inst.dir, `neoforge-${nfv}-installer.jar`);
  await _download(installerUrl, installerDest);

  await new Promise((resolve, reject) => {
    const proc = childProcess.spawn('java', ['-jar', installerDest, '--installServer'], {
      cwd:   inst.dir,
      stdio: 'inherit',
    });
    proc.on('close', code => code === 0 ? resolve() : reject(new Error(`NeoForge installer exited ${code}`)));
  });

  inst.type    = 'neoforge';
  inst.version = mc;
  // NeoForge uses a run script; find it
  const runSh  = path.join(inst.dir, 'run.sh');
  if (fs.existsSync(runSh)) {
    // Wrap the run script so ServerInstance can still use java -jar pattern
    // by symlinking / writing a launcher shim JAR path isn't needed —
    // NeoForge 1.17+ writes a unix_args.txt; we keep jarFile for the user to override
    inst.jarFile = `neoforge-${nfv}-shim.jar`;
    // Write a tiny wrapper noting the user should use the run script for full NeoForge
    fs.writeFileSync(path.join(inst.dir, '_NEOFORGE_README.txt'),
      `NeoForge installed.\nTo start: sh run.sh\nOr use __start_server which will pick up the run script automatically.\n`);
  }
  fs.mkdirSync(path.join(inst.dir, 'mods'), { recursive: true });
  return { neoforgeVersion: nfv, mcVersion: mc };
}

